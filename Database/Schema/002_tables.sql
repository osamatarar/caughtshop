CREATE TABLE IF NOT EXISTS caught.products (
    product_id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1001 INCREMENT BY 1) PRIMARY KEY,
    creator_id integer NOT NULL,
    public_number integer NOT NULL,
    name varchar(200) NOT NULL,
    description varchar(2000) NOT NULL,
    image_url varchar(2000) NOT NULL,
    price numeric(12, 2) NOT NULL,
    currency varchar(3) NOT NULL,
    tiktok_url varchar(2000) NOT NULL,
    amazon_url varchar(2000) NOT NULL DEFAULT '',
    brand_url varchar(2000) NOT NULL DEFAULT '',
    availability varchar(20) NOT NULL,
    backup_product_id integer NULL,
    created_by integer NOT NULL,
    created_date timestamptz NOT NULL DEFAULT now(),
    updated_by integer NOT NULL,
    updated_date timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_products_creator_public_number UNIQUE (creator_id, public_number),
    CONSTRAINT ck_products_public_number CHECK (public_number > 0),
    CONSTRAINT ck_products_name CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_products_description CHECK (length(btrim(description)) > 0),
    CONSTRAINT ck_products_price CHECK (price > 0),
    CONSTRAINT ck_products_currency CHECK (currency IN ('USD', 'EUR', 'GBP', 'CAD', 'AUD')),
    CONSTRAINT ck_products_availability CHECK (availability IN ('available', 'out_of_stock')),
    CONSTRAINT ck_products_image_url CHECK (image_url ~ '^https://'),
    CONSTRAINT ck_products_tiktok_url CHECK (tiktok_url ~ '^https://'),
    CONSTRAINT ck_products_amazon_url CHECK (amazon_url = '' OR amazon_url ~ '^https://'),
    CONSTRAINT ck_products_brand_url CHECK (brand_url = '' OR brand_url ~ '^https://'),
    CONSTRAINT ck_products_backup_not_self CHECK (backup_product_id IS NULL OR backup_product_id <> product_id),
    CONSTRAINT fk_products_creator FOREIGN KEY (creator_id) REFERENCES caught.creators (creator_id),
    CONSTRAINT fk_products_backup FOREIGN KEY (backup_product_id) REFERENCES caught.products (product_id),
    CONSTRAINT fk_products_created_by FOREIGN KEY (created_by) REFERENCES caught.creators (creator_id),
    CONSTRAINT fk_products_updated_by FOREIGN KEY (updated_by) REFERENCES caught.creators (creator_id)
);

