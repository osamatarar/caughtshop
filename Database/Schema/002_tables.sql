-- Caught tables, checks, and audit trigger. Run after 001_schema.sql. Safe to run more than once.

CREATE TABLE IF NOT EXISTS caught.creators (
    creator_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(120) NOT NULL,
    email varchar(254) NOT NULL,
    password_hash varchar(300) NOT NULL,
    handle varchar(30) NOT NULL,
    tiktok_url varchar(2000) NOT NULL DEFAULT '',
    instagram_url varchar(2000) NOT NULL DEFAULT '',
    youtube_url varchar(2000) NOT NULL DEFAULT '',
    created_by integer NOT NULL,
    created_date timestamptz NOT NULL DEFAULT now(),
    updated_by integer NOT NULL,
    updated_date timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_creators_email UNIQUE (email),
    CONSTRAINT uq_creators_handle UNIQUE (handle),
    CONSTRAINT ck_creators_full_name CHECK (length(btrim(full_name)) > 0),
    CONSTRAINT ck_creators_email CHECK (length(email) > 3 AND position('@' IN email) > 1),
    CONSTRAINT ck_creators_handle CHECK (handle ~ '^[a-z0-9_]{3,30}$'),
    CONSTRAINT ck_creators_tiktok_url CHECK (tiktok_url = '' OR tiktok_url ~ '^https://'),
    CONSTRAINT ck_creators_instagram_url CHECK (instagram_url = '' OR instagram_url ~ '^https://'),
    CONSTRAINT ck_creators_youtube_url CHECK (youtube_url = '' OR youtube_url ~ '^https://'),
    CONSTRAINT fk_creators_created_by FOREIGN KEY (created_by) REFERENCES caught.creators (creator_id),
    CONSTRAINT fk_creators_updated_by FOREIGN KEY (updated_by) REFERENCES caught.creators (creator_id)
);

ALTER TABLE caught.creators ADD COLUMN IF NOT EXISTS tiktok_url varchar(2000) NOT NULL DEFAULT '';
ALTER TABLE caught.creators ADD COLUMN IF NOT EXISTS instagram_url varchar(2000) NOT NULL DEFAULT '';
ALTER TABLE caught.creators ADD COLUMN IF NOT EXISTS youtube_url varchar(2000) NOT NULL DEFAULT '';
ALTER TABLE caught.creators DROP CONSTRAINT IF EXISTS ck_creators_tiktok_url;
ALTER TABLE caught.creators DROP CONSTRAINT IF EXISTS ck_creators_instagram_url;
ALTER TABLE caught.creators DROP CONSTRAINT IF EXISTS ck_creators_youtube_url;
