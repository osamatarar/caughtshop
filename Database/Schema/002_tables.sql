CREATE OR REPLACE FUNCTION caught.touch_updated_date()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = caught
AS $fn$
BEGIN
    NEW.updated_date := now();
    RETURN NEW;
END;
$fn$;

CREATE OR REPLACE FUNCTION caught.enforce_product_backup()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = caught
AS $fn$
DECLARE
    backup_creator integer;
    backup_availability varchar(20);
BEGIN
    IF NEW.availability = 'out_of_stock' THEN
        IF TG_OP = 'UPDATE' AND EXISTS (
            SELECT 1
            FROM caught.products
            WHERE products.backup_product_id = NEW.product_id
              AND products.product_id <> NEW.product_id
        ) THEN
            RAISE EXCEPTION 'This product is a backup for another product.'
                USING ERRCODE = '22023';
        END IF;

        IF NEW.backup_product_id IS NULL THEN
            RAISE EXCEPTION 'Choose a backup product.'
                USING ERRCODE = '22023';
        END IF;

        SELECT products.creator_id, products.availability
        INTO backup_creator, backup_availability
        FROM caught.products
        WHERE products.product_id = NEW.backup_product_id;

        IF backup_creator IS NULL OR backup_creator <> NEW.creator_id THEN
            RAISE EXCEPTION 'Backup product must belong to the same creator.'
                USING ERRCODE = '22023';
        END IF;

        IF backup_availability <> 'available' THEN
            RAISE EXCEPTION 'Backup product must be in stock.'
                USING ERRCODE = '22023';
        END IF;

        RETURN NEW;
    END IF;

    IF NEW.backup_product_id IS NOT NULL THEN
        RAISE EXCEPTION 'Backup product is only allowed when the product is out of stock.'
            USING ERRCODE = '22023';
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE OR REPLACE FUNCTION caught.enforce_video_owner()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = caught
AS $fn$
DECLARE
    product_creator integer;
BEGIN
    SELECT products.creator_id
    INTO product_creator
    FROM caught.products
    WHERE products.product_id = NEW.product_id;

    IF product_creator IS NULL OR product_creator <> NEW.creator_id THEN
        RAISE EXCEPTION 'Choose a product.'
            USING ERRCODE = '22023';
    END IF;

    RETURN NEW;
END;
$fn$;

DO $fn$
DECLARE
    table_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY['creators', 'products', 'videos', 'sale_alerts']
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%s_touch ON caught.%I', table_name, table_name);
        EXECUTE format(
            'CREATE TRIGGER trg_%s_touch BEFORE UPDATE ON caught.%I FOR EACH ROW EXECUTE FUNCTION caught.touch_updated_date()',
            table_name,
            table_name);
    END LOOP;
END;
$fn$;

DROP TRIGGER IF EXISTS trg_products_backup ON caught.products;
CREATE TRIGGER trg_products_backup
    BEFORE INSERT OR UPDATE ON caught.products
    FOR EACH ROW
    EXECUTE FUNCTION caught.enforce_product_backup();

DROP TRIGGER IF EXISTS trg_videos_owner ON caught.videos;
CREATE TRIGGER trg_videos_owner
    BEFORE INSERT OR UPDATE ON caught.videos
    FOR EACH ROW
    EXECUTE FUNCTION caught.enforce_video_owner();
