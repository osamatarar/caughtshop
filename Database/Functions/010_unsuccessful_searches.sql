-- Unsuccessful public catalog searches. Run after 002_tables.sql. Safe to run more than once.

CREATE TABLE IF NOT EXISTS caught.unsuccessful_searches (
    unsuccessful_search_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id integer NOT NULL,
    query_text varchar(200) NOT NULL,
    searched_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_unsuccessful_searches_query CHECK (length(btrim(query_text)) > 0),
    CONSTRAINT fk_unsuccessful_searches_creator FOREIGN KEY (creator_id) REFERENCES caught.creators (creator_id)
);

CREATE INDEX IF NOT EXISTS ix_unsuccessful_searches_creator_searched
    ON caught.unsuccessful_searches (creator_id, searched_at);

DROP FUNCTION IF EXISTS caught.insert_unsuccessful_search(text, text);

CREATE OR REPLACE FUNCTION caught.insert_unsuccessful_search(
    p_handle text,
    p_query text
)
RETURNS void
LANGUAGE plpgsql
SET search_path = caught
AS $fn$
DECLARE
    owner_id integer;
    normalized text;
BEGIN
    normalized := lower(btrim(regexp_replace(COALESCE(p_query, ''), '^#', '')));
    IF length(normalized) = 0 THEN
        RAISE EXCEPTION 'Enter a search term.'
            USING ERRCODE = '22023';
    END IF;

    IF length(normalized) > 200 THEN
        RAISE EXCEPTION 'Use a shorter search term.'
            USING ERRCODE = '22023';
    END IF;

    SELECT creators.creator_id
    INTO owner_id
    FROM caught.creators
    WHERE creators.handle = lower(btrim(COALESCE(p_handle, '')));

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Creator was not found.'
            USING ERRCODE = 'P0002';
    END IF;

    INSERT INTO caught.unsuccessful_searches (creator_id, query_text, searched_at)
    VALUES (owner_id, normalized, now());
END;
$fn$;

DROP FUNCTION IF EXISTS caught.unsuccessful_search_report(integer, date, date, text);

CREATE OR REPLACE FUNCTION caught.unsuccessful_search_report(
    p_creator_id integer,
    p_start date,
    p_end date,
    p_time_zone text
)
RETURNS TABLE (
    kind text,
    day_key text,
    query_text text,
    search_count integer
)
LANGUAGE plpgsql
SET search_path = caught
AS $fn$
#variable_conflict use_column
BEGIN
    IF p_time_zone IS NULL OR length(btrim(p_time_zone)) = 0 THEN
        RAISE EXCEPTION 'Choose a time zone.'
            USING ERRCODE = '22023';
    END IF;

    IF p_start IS NULL OR p_end IS NULL OR p_end < p_start THEN
        RAISE EXCEPTION 'Start date must be on or before the end date.'
            USING ERRCODE = '22023';
    END IF;

    IF (p_end - p_start) > 365 THEN
        RAISE EXCEPTION 'Choose a range of 366 days or fewer.'
            USING ERRCODE = '22023';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM caught.creators WHERE creators.creator_id = p_creator_id) THEN
        RAISE EXCEPTION 'Creator was not found.'
            USING ERRCODE = 'P0002';
    END IF;

    BEGIN
        PERFORM now() AT TIME ZONE p_time_zone;
    EXCEPTION
        WHEN invalid_parameter_value THEN
            RAISE EXCEPTION 'Choose a time zone.'
                USING ERRCODE = '22023';
    END;

    RETURN QUERY
    WITH misses AS (
        SELECT
            (searches.searched_at AT TIME ZONE p_time_zone)::date AS search_date,
            searches.query_text
        FROM caught.unsuccessful_searches AS searches
        WHERE searches.creator_id = p_creator_id
          AND searches.searched_at >= (p_start::timestamp AT TIME ZONE p_time_zone)
          AND searches.searched_at < ((p_end + 1)::timestamp AT TIME ZONE p_time_zone)
    )
    SELECT
        'day'::text,
        to_char(series.day::date, 'YYYY-MM-DD'),
        NULL::text,
        COALESCE(COUNT(misses.search_date), 0)::integer
    FROM generate_series(p_start, p_end, interval '1 day') AS series(day)
    LEFT JOIN misses ON misses.search_date = series.day::date
    GROUP BY series.day
    UNION ALL
    SELECT
        'query'::text,
        NULL::text,
        misses.query_text,
        COUNT(*)::integer
    FROM misses
    GROUP BY misses.query_text
    ORDER BY 1, 4 DESC NULLS LAST, 3;
END;
$fn$;
